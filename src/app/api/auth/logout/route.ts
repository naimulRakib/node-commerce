// নেক্সট.জেএস (Next.js) এর সার্ভার রেসপন্স অবজেক্ট।
import { NextResponse } from "next/server";
// ইউজারের ব্রাউজার থেকে সেশন কুকি মুছে ফেলার জন্য হেল্পার ফাংশন।
import { clearSessionCookie } from "@/lib/auth";

// ─── লগ-আউট এপিআই এন্ডপয়েন্ট (Logout API Endpoint) ──────────────
// এটি একটি POST রিকোয়েস্ট হ্যান্ডলার, যা ইউজারের সেশন ডেস্ট্রয় (Destroy) করে।
export async function POST() {
  try {
    // ১. কুকি ক্লিয়ারিং (Cookie Clearing):
    // সার্ভার থেকে ইউজারের ব্রাউজারকে নির্দেশ দেওয়া হয় যেন সে অথেনটিকেশন কুকিটি মুছে ফেলে বা এক্সপায়ার (Expire) করে দেয়।
    await clearSessionCookie();
    
    // ২. সফল রেসপন্স (Successful Response):
    return NextResponse.json({ message: "Logout successful" });
  } catch (error) {
    // ৩. এক্সেপশন হ্যান্ডলিং (Exception Handling):
    console.error("[POST /api/auth/logout]", error);
    return NextResponse.json(
      { error: "Internal Server Error" },
      { status: 500 }
    );
  }
}

